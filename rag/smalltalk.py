"""闲聊 / 身份类问题的短路识别。

为什么要在检索之前分流：
  1. 这类问题没有"知识库答案"，检索必然返回一堆无关块——实测问"你是什么"，
     右栏弹出 5 个 0.588 分的代码片段，用户会以为系统是拿这些回答他的
  2. 白跑一次 embedding + rerank（热态 0.4~0.6s，冷态更多），且拒答门槛
     还可能误判（0.51 > 0.5，刚好过线，于是走完整生成流程）

判据用正则而不是让 LLM 分类：这一步在请求最前面，必须零成本、零延迟、
零 token；宁可漏判（漏了就退回正常 RAG 流程，prompt 第 7/8 条也兜得住），
不可错判（把真实提问当成闲聊吞掉）。
所以模式都写得很紧：整句匹配 + 排除问号之外的内容。
"""

import re

_IDENTITY = re.compile(
    r"^(你|您)(是|叫)(谁|什么|啥|哪位)|"
    r"^(你|您)(是|做)?(什么|啥)(的)?(工作)?[的了吗呢啊呀?？!！。.~～\s]*$|"
    r"^(你|您)(到底|究竟)?(是)?(干|做)(什么|啥)(的)?[的了吗呢啊呀?？!！。.~～\s]*$|"
    r"^(你|您)(能|会|可以)(做|干)(什么|啥)|"
    r"^(你|您)(有|是)什么(用|功能|能力)|"
    r"^(介绍|说说)一下(你|您)(自己)?[?？。.!！~～\s]*$|"
    r"^(你|您)(是|不是)(什么|啥)?(ai|AI|人工智能|机器人|模型|程序|助手)[吗呢啊?？!！。.\s]*$"
)

_GREETING = re.compile(r"^(你好|您好|hi|hello|嗨|哈喽|在吗|在不在)[!！。.？?~～\s]*$", re.I)
_THANKS = re.compile(r"^(谢谢|感谢|多谢|谢了|thanks|thank\s*you|3q)[!！。.？?~～\s]*$", re.I)
_BYE = re.compile(r"^(再见|拜拜|bye|goodbye|晚安)[!！。.？?~～\s]*$", re.I)


def is_smalltalk(question: str) -> bool:
    q = question.strip()
    if not q or len(q) > 20:      # 长句子一律不当闲聊，交给 RAG
        return False
    return any(p.match(q) for p in (_IDENTITY, _GREETING, _THANKS, _BYE))


def smalltalk_answer(question: str) -> str:
    """固定话术，不调 LLM：这类回答不需要推理，调模型只是多等 1 秒。"""
    q = question.strip()
    if _GREETING.match(q):
        return (
            "你好，我是基于本知识库文档的问答助手。"
            "可以问我文档里的概念、流程或配置，回答会标注来源页码。"
        )
    if _THANKS.match(q):
        return "不客气。还有其他想了解的，直接问就好。"
    if _BYE.match(q):
        return "再见。需要时随时回来问。"
    return (
        "我是基于本知识库文档的问答助手：只根据已入库的文档内容回答，"
        "并在句末标注来源编号；材料里没有的内容会直接说无法回答。"
        "可以问我文档里的概念、流程或配置。"
    )
